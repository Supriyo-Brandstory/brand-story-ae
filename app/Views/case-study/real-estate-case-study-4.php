<section class="challenge-sec">
    <div class="container text-md-start text-center">
        <h2 class="text-white mb-3">Our <span class="text-purple">Solutions</span></h2>
        <p class="mb-0 text-white fs-20"><b>PPC Campaign Management:</b> We rebuilt the ad account from the ground up. Keywords were grouped by project, unit type and buyer intent. A strong negative keyword list cut out renters and job seekers. Ads targeted investors and buyers in the UAE and in key overseas markets. We tested ad copy and creatives every month. Conversion tracking showed which clicks became leads, so budget moved to the best performers.</p><br>
        <p class="mb-0 text-white fs-20"><b>Landing Page Optimization:</b> We built a dedicated landing page for each project and campaign. Each page matched its ad and showed the price range, payment plan, floor plans and a brochure download. A short enquiry form and a WhatsApp button made it easy to get in touch. We tested layouts and buttons to raise the number of visitors who enquired.</p><br>
        <p class="mb-0 text-white fs-20"><b>Technical SEO & Indexing:</b> We fixed crawl errors and 404 pages. We set up an XML sitemap, robots.txt and canonical tags. Key pages got optimized meta titles, descriptions and schema markup. We submitted the important pages through Search Console for faster indexing.</p><br>
        <p class="mb-0 text-white fs-20"><b>On-Page SEO & Content:</b> We planned keywords for every project, unit type and area page. Headings (H1 - H3) and page content were improved. Internal links were rebuilt to guide search engines and buyers to the key pages. We also published blogs on Downtown Dubai living, off-plan buying, payment plans and investment returns. These answered buyer questions and led readers to the project pages.</p>
    </div>
</section>

