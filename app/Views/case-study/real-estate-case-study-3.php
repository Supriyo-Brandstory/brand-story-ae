        <h2 class="text-white mb-3">Our <span class="text-purple">Solutions</span></h2>
        <p class="mb-0 text-white fs-20"><b>Market Entry & Audience Strategy:</b> We studied how NRIs in the UAE search for and choose property back home. We built buyer groups by home state, budget and investment goal. This shaped every message, ad and page we created for the Dubai launch.</p><br>
        <p class="mb-0 text-white fs-20"><b>PPC Campaign Management:</b> We set up paid campaigns aimed at NRIs living in the UAE. Ads were targeted by location, interest and buyer intent. Each campaign led to a dedicated landing page for the project, with a simple enquiry form. Regular testing and tracking helped us cut wasted spend and improve lead quality.</p><br>
        <p class="mb-0 text-white fs-20"><b>Landing Pages & Search Visibility:</b> We created project pages made for NRI buyers, with plot details, approvals, pricing and location highlights. We also improved meta titles, descriptions and internal linking, so buyers could find G Square when searching for South Indian plots and villas from Dubai.</p><br>
        <p class="mb-0 text-white fs-20"><b>Social Media Strategy:</b> We built a content plan around project updates, buyer stories, and the process of buying remotely. Posts were made to connect with NRI communities in the UAE. Consistent posting and targeted campaigns helped the brand stay in front of the right buyers.</p>
    </div>
</section>

