            <h2>The Real Pain Points</h2>

            <div class="cs-painpoints-grid">

                <div class="cs-card">
                    <span>01</span>
                    <h3>No Presence in the UAE</h3>
                    <p>G Square was unknown to NRI buyers in Dubai. Its name did not show up in local searches, and there was no content made for this audience. Buyers had little reason to trust a brand they had never heard of.</p>
                </div>

                <div class="cs-card">
                    <span>02</span>
                    <h3>Low Enquiries from NRIs</h3>
                    <p>Ads and pages were not built for NRI buyers. Messaging did not speak to their needs, such as safe investment, clear legal titles and remote buying. As a result, few quality leads came in.</p>
                </div>

                <div class="cs-card">
                    <span>03</span>
                    <h3>Trust and Information Gaps</h3>
                    <p>Buyers abroad could not easily check project details. Plot layouts, approvals, prices and locations were hard to find. Without clear proof, it was difficult for them to feel confident about buying.</p>
                </div>

                <div class="cs-card">
                    <span>04</span>
                    <h3>Weak Social Media Reach</h3>
                    <p>G Square had no social media strategy for the UAE. Content did not connect with NRI communities, and there was no regular posting or audience targeting. This limited reach and missed chances to build interest.</p>
                </div>

            </div>
