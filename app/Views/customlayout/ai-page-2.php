      window.addEventListener('scroll', updateActivePillar);
      updateActivePillar();

      // View More / View Less button handler for Why Choose Us section
      document.querySelectorAll('.mumbai-btn-view-more').forEach(function(btn) {
        btn.addEventListener('click', function(e) {
          e.preventDefault();
          const section = btn.closest('section') || btn.closest('.mumbai-choose-us-section');
          if (!section) return;
          const extraItems = section.querySelectorAll('.mumbai-choose-us-extra, .extra-item');
          btn.classList.toggle('active');
          let isExpanded = false;
          extraItems.forEach(function(item) {
            item.classList.toggle('d-none');
            if (!item.classList.contains('d-none')) {
              isExpanded = true;
            }
          });
          const btnText = btn.querySelector('span');
          const svg = btn.querySelector('svg');
          if (btnText) {
            if (isExpanded) {
              btnText.textContent = 'View Less';
              if (svg) svg.style.transform = 'rotate(180deg)';
            } else {
              btnText.textContent = 'View More';
              if (svg) svg.style.transform = 'rotate(0deg)';
            }
          }
        });
      });
    });

  </script>

</div>
