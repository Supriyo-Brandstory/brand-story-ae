        // Update tab buttons
        const tabs = document.querySelectorAll('.faq-tab');
        tabs.forEach(tab => {
            tab.classList.remove('active');
            if (tab.getAttribute('onclick').includes(`'${cat}'`)) {
                tab.classList.add('active');
            }
        });

