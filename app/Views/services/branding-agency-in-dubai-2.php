      function updateActivePillar() {
        let currentId = '';
        const scrollPos = window.pageYOffset || document.documentElement.scrollTop;

        pillarCards.forEach(card => {
          const cardTop = card.offsetTop - 150;
          const cardHeight = card.offsetHeight;
          if (scrollPos >= cardTop && scrollPos < cardTop + cardHeight) {
            currentId = card.getAttribute('id');
          }
        });

        pillarLinks.forEach(link => {
          link.classList.remove('active');
          if (currentId && link.getAttribute('href') === '#' + currentId) {
            link.classList.add('active');
          }
        });
      }

      window.addEventListener('scroll', updateActivePillar);
      updateActivePillar();
    });
