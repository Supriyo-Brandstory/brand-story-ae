<script>
    document.addEventListener('DOMContentLoaded', function() {
        var industrySwiper = new Swiper('.industry-swiper', {
            slidesPerView: 1,
            spaceBetween: 50,
            loop: true,
            speed: 1000,
            autoplay: {
                delay: 6000,
                disableOnInteraction: false,
                pauseOnMouseEnter: true,
            },
            pagination: {
                el: '.industry-pagination',
                type: 'fraction',
                renderFraction: function (currentClass, totalClass) {
                    return '<span class="' + currentClass + '"></span>' +
                           ' / ' +
                           '<span class="' + totalClass + '"></span>';
                }
            },
            navigation: {
                nextEl: '.industry-next',
                prevEl: '.industry-prev',
            },
            // Additional pagination for mobile dots
            on: {
                init: function () {
                    // Inject bullets if mobile
                    this.params.pagination.el = window.innerWidth < 991 ? '.industry-pagination-dots' : '.industry-pagination';
                    if (window.innerWidth < 991) {
                        this.params.pagination.type = 'bullets';
                        this.params.pagination.clickable = true;
                    }
                    this.pagination.update();
                },
                resize: function () {
                    // Switch pagination type on resize
                    var isMobile = window.innerWidth < 991;
                    this.params.pagination.el = isMobile ? '.industry-pagination-dots' : '.industry-pagination';
                    this.params.pagination.type = isMobile ? 'bullets' : 'fraction';
                    this.pagination.destroy();
                    this.pagination.init();
                    this.pagination.render();
                    this.pagination.update();
                }
            }
        });
    });
</script>